-- CotizaT — actualización de n9f2a5b8c3d6 a o2e4a6c8b1d3
--
-- Registro durable de errores internos (Fase 0.2 de la hoja de ruta
-- 2026-10-20): la tabla `public.errores_internos` y la función
-- `cotizat_security.registrar_error_interno`.
--
-- Hasta ahora las excepciones que terminan en 500 solo quedaban en un
-- buffer en memoria de cada instancia serverless: al reiniciar se perdían
-- y un fallo de madrugada era invisible a la mañana siguiente. Esta tabla
-- es el sumidero propio, sin servicios externos:
--
--   * Una fila por **huella** (metodo + ruta saneada + tipo + mensaje): el
--     mismo fallo repetido solo suma `ocurrencias` y refresca la traza.
--     `resuelto_en` lo marca el operador desde el panel (Sistema › Estado);
--     si el fallo reaparece, la marca se limpia sola y vuelve a avisar.
--   * La escritura no depende de ninguna sesión: un 500 puede ser de un
--     anónimo. Por eso **nadie tiene INSERT directo**: la única puerta es
--     la función SECURITY DEFINER de abajo, que hace el UPSERT por huella
--     y devuelve si toca avisar por correo (huella nueva o resucitada).
--   * Leer, marcar resuelto y podar es solo del operador
--     (`cotizat.es_operador`), como el buzón de soporte: las trazas son
--     diagnóstico interno, no datos de clientes.
--
-- Riesgo operativo nulo para lo que ya funciona: es una tabla nueva que
-- nada de lo existente lee. Si el código se despliega antes que este SQL,
-- el registro simplemente no persiste (best-effort) y el panel sigue con
-- el buffer en memoria hasta aplicarlo; solo `/readyz` señalará la
-- versión hasta que se ejecute.
--
-- Ejecutar una sola vez en el SQL Editor de Supabase con el rol
-- administrativo (nunca con `cotizat_runtime` ni con `cotizat_app`) y solo si
-- la versión actual es n9f2a5b8c3d6. Deja el head en o2e4a6c8b1d3
-- (`EXPECTED_ALEMBIC_HEAD = o2e4a6c8b1d3`).

