-- CotizaT — actualización de h1c4b7e9a3d2 a i4d7c1b8e2f5
--
-- Buzón de soporte (`public.mensajes_soporte`). El cliente escribe desde el
-- botón «Soporte» de la aplicación (o desde /soporte, sin cuenta) y el mensaje
-- se guarda aquí ANTES de intentar el aviso por Resend: si el proveedor de
-- correo falla, el mensaje no se pierde. El titular lo lee en el panel
-- (Clientes › Buzón de soporte) y responde desde su buzón de correo, porque el
-- aviso sale con `reply-to` del cliente.
--
-- Por qué no es una tabla de tenant, aunque tenga `organizacion_id`:
-- quien escribe puede no tener cuenta todavía; la organización es opcional con
-- `ON DELETE SET NULL`, de modo que dar de baja una empresa no borra la
-- conversación con esa persona. La lectura y la gestión son de operador; el
-- INSERT queda abierto a la aplicación (formulario público) pero forzando
-- `estado = 'nuevo'`. No hay permiso de DELETE: un mensaje se marca, no se
-- borra.
--
-- Ejecutar una sola vez en el SQL Editor de Supabase con el rol
-- administrativo (nunca con `cotizat_runtime` ni con `cotizat_app`) y solo si
-- la versión actual es h1c4b7e9a3d2.

BEGIN;

DO $$
DECLARE
  v_version text;
BEGIN
  SELECT version_num INTO v_version FROM public.alembic_version LIMIT 1;
  IF v_version IS DISTINCT FROM 'h1c4b7e9a3d2' THEN
    RAISE EXCEPTION
      'Se esperaba alembic_version h1c4b7e9a3d2 antes de i4d7c1b8e2f5; se encontró %',
      COALESCE(v_version, '<vacío>');
  END IF;
END
$$;

CREATE TABLE IF NOT EXISTS public.mensajes_soporte (
  id                   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre               varchar(200) NOT NULL DEFAULT '',
  email                varchar(254) NOT NULL DEFAULT '',
  organizacion_id      integer REFERENCES public.organizaciones(id) ON DELETE SET NULL,
  usuario_id           integer REFERENCES public.usuarios(id) ON DELETE SET NULL,
  tipo                 varchar(20)  NOT NULL DEFAULT 'consulta',
  asunto               varchar(200) NOT NULL DEFAULT '',
  mensaje              text         NOT NULL DEFAULT '',
  pagina               varchar(500) NOT NULL DEFAULT '',
  estado               varchar(20)  NOT NULL DEFAULT 'nuevo',
  nota_interna         text         NOT NULL DEFAULT '',
  atendido_por_email   varchar(254) NOT NULL DEFAULT '',
  atendido_at          timestamp,
  aviso_enviado        boolean      NOT NULL DEFAULT false,
  ip_hash              varchar(64)  NOT NULL DEFAULT '',
  created_at           timestamp    NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at           timestamp,
  CONSTRAINT ck_mensaje_soporte_tipo_valido CHECK (
    tipo IN ('consulta', 'problema', 'queja', 'sugerencia', 'facturacion', 'otro')
  ),
  CONSTRAINT ck_mensaje_soporte_estado_valido CHECK (
    estado IN ('nuevo', 'en_proceso', 'resuelto')
  )
);

CREATE INDEX IF NOT EXISTS ix_mensajes_soporte_estado
  ON public.mensajes_soporte (estado, created_at);
CREATE INDEX IF NOT EXISTS ix_mensajes_soporte_email
  ON public.mensajes_soporte (email);
CREATE INDEX IF NOT EXISTS ix_mensajes_soporte_org
  ON public.mensajes_soporte (organizacion_id, created_at);

REVOKE ALL ON TABLE public.mensajes_soporte FROM PUBLIC;
ALTER TABLE public.mensajes_soporte ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.mensajes_soporte FORCE ROW LEVEL SECURITY;

-- Sin DELETE a propósito: un mensaje se marca como resuelto, no se borra.
GRANT SELECT, INSERT, UPDATE ON TABLE public.mensajes_soporte TO cotizat_app;
GRANT USAGE, SELECT ON SEQUENCE public.mensajes_soporte_id_seq TO cotizat_app;

DROP POLICY IF EXISTS cotizat_ms_select_operator ON public.mensajes_soporte;
CREATE POLICY cotizat_ms_select_operator ON public.mensajes_soporte
  FOR SELECT TO cotizat_app
  USING (COALESCE(pg_catalog.current_setting('cotizat.es_operador', true) = 'on', FALSE));

DROP POLICY IF EXISTS cotizat_ms_update_operator ON public.mensajes_soporte;
CREATE POLICY cotizat_ms_update_operator ON public.mensajes_soporte
  FOR UPDATE TO cotizat_app
  USING (COALESCE(pg_catalog.current_setting('cotizat.es_operador', true) = 'on', FALSE));

-- El formulario público no tiene sesión ni marca de operador: puede insertar
-- un mensaje nuevo y nada más (ni fingir gestión previa ni leer lo ajeno).
DROP POLICY IF EXISTS cotizat_ms_insert_publico ON public.mensajes_soporte;
CREATE POLICY cotizat_ms_insert_publico ON public.mensajes_soporte
  FOR INSERT TO cotizat_app
  WITH CHECK (
    estado = 'nuevo' AND atendido_por_email = '' AND nota_interna = ''
  );

UPDATE public.alembic_version
SET version_num = 'i4d7c1b8e2f5'
WHERE version_num = 'h1c4b7e9a3d2';

COMMIT;

