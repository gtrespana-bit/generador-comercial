-- Actualiza también el borrado verificado de una organización: mensajes e
-- hilos deben desaparecer antes de licencias/membresías/organización.
CREATE OR REPLACE FUNCTION cotizat_security.baja_organizacion(
  p_organization_id integer
) RETURNS void LANGUAGE plpgsql SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_role text;
BEGIN
  IF COALESCE(current_setting('cotizat.organization_id', true), '')
       <> p_organization_id::text THEN
    RAISE EXCEPTION
      'La baja no coincide con la organización de la sesión.'
      USING ERRCODE = '42501';
  END IF;

  v_role := cotizat_security.membership_role(p_organization_id);
  IF v_role IS DISTINCT FROM 'propietario' THEN
    RAISE EXCEPTION
      'Solo el propietario puede dar de baja la organización.'
      USING ERRCODE = '42501';
  END IF;

  DELETE FROM public.enlaces_propuesta WHERE organizacion_id = p_organization_id;
  DELETE FROM public.pagos WHERE organizacion_id = p_organization_id;
  DELETE FROM public.cambio_alcance_items WHERE organizacion_id = p_organization_id;
  DELETE FROM public.cambios_alcance WHERE organizacion_id = p_organization_id;
  DELETE FROM public.proyectos WHERE organizacion_id = p_organization_id;
  DELETE FROM public.notas_seguimiento WHERE organizacion_id = p_organization_id;
  DELETE FROM public.presupuesto_anexos WHERE organizacion_id = p_organization_id;
  DELETE FROM public.borradores_presupuesto WHERE organizacion_id = p_organization_id;
  DELETE FROM public.presupuesto_versiones WHERE organizacion_id = p_organization_id;
  DELETE FROM public.descomposicion_filas WHERE organizacion_id = p_organization_id;
  DELETE FROM public.descomposiciones_partida WHERE organizacion_id = p_organization_id;
  DELETE FROM public.mediciones WHERE organizacion_id = p_organization_id;
  DELETE FROM public.presupuesto_item_productos WHERE organizacion_id = p_organization_id;
  DELETE FROM public.presupuesto_items WHERE organizacion_id = p_organization_id;
  DELETE FROM public.capitulos WHERE organizacion_id = p_organization_id;
  DELETE FROM public.presupuestos WHERE organizacion_id = p_organization_id;
  DELETE FROM public.factura_items WHERE organizacion_id = p_organization_id;
  DELETE FROM public.factura_capitulos WHERE organizacion_id = p_organization_id;
  DELETE FROM public.facturas WHERE organizacion_id = p_organization_id;
  DELETE FROM public.clientes WHERE organizacion_id = p_organization_id;
  DELETE FROM public.partidas WHERE organizacion_id = p_organization_id;
  DELETE FROM public.productos WHERE organizacion_id = p_organization_id;
  DELETE FROM public.recursos WHERE organizacion_id = p_organization_id;
  DELETE FROM public.plantillas WHERE organizacion_id = p_organization_id;
  DELETE FROM public.recetas_estancia WHERE organizacion_id = p_organization_id;
  DELETE FROM public.categorias_partidas WHERE organizacion_id = p_organization_id;
  DELETE FROM public.archivos_almacenados WHERE organizacion_id = p_organization_id;
  DELETE FROM public.invitaciones_organizacion WHERE organizacion_id = p_organization_id;
  DELETE FROM public.configuracion WHERE organizacion_id = p_organization_id;
  DELETE FROM public.compras_plan WHERE organizacion_id = p_organization_id;
  DELETE FROM public.eventos_auditoria WHERE organizacion_id = p_organization_id;
  DELETE FROM public.mensajes_ia WHERE organizacion_id = p_organization_id;
  DELETE FROM public.conversaciones_ia WHERE organizacion_id = p_organization_id;
  DELETE FROM public.licencias WHERE organizacion_id = p_organization_id;
  DELETE FROM public.membresias WHERE organizacion_id = p_organization_id;
  DELETE FROM public.organizaciones WHERE id = p_organization_id;
END
$$;

ALTER FUNCTION cotizat_security.baja_organizacion(integer) OWNER TO CURRENT_USER;
REVOKE ALL ON FUNCTION cotizat_security.baja_organizacion(integer) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION cotizat_security.baja_organizacion(integer) TO cotizat_app;

