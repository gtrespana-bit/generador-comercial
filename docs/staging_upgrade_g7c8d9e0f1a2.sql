CREATE TABLE public.conversaciones_ia (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organizacion_id integer NOT NULL REFERENCES public.organizaciones(id) ON DELETE RESTRICT,
  public_id varchar(64) NOT NULL,
  usuario_id integer NULL REFERENCES public.usuarios(id) ON DELETE SET NULL,
  usuario_email varchar(254) NOT NULL DEFAULT '',
  titulo varchar(180) NOT NULL DEFAULT '',
  pagina_inicio varchar(240) NOT NULL DEFAULT '',
  estado varchar(20) NOT NULL DEFAULT 'activa',
  created_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  ultimo_mensaje_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  expires_at timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
