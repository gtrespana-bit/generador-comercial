  CONSTRAINT ck_mensaje_ia_orden_no_negativo CHECK (orden >= 0),
  CONSTRAINT uq_mensaje_ia_conversacion_orden UNIQUE (conversacion_id, orden),
  CONSTRAINT uq_mensaje_ia_conversacion_turno_rol
    UNIQUE (conversacion_id, rol, turn_id)
